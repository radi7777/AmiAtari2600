u16 palette_to_rgb12(u32 rgb)
{
    unsigned r = (unsigned)((rgb >> 16) & 0xFF);
    unsigned g = (unsigned)((rgb >> 8) & 0xFF);
    unsigned b = (unsigned)(rgb & 0xFF);
    r = (r + 8) / 17; g = (g + 8) / 17; b = (b + 8) / 17;   /* 0..255 -> 0..15 */
    return (u16)((r << 8) | (g << 4) | b);
}
